from __future__ import annotations
from typing import Literal
from uuid import uuid4
import os
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

app = FastAPI(title="CounterDiab Demo API", version="1.0.0", description="Transparent educational rules-based assessment demo. Not a medical device.")
origins = [x.strip() for x in os.getenv("CORS_ORIGINS", "http://localhost:3000").split(",") if x.strip()]
app.add_middleware(CORSMiddleware, allow_origins=origins, allow_credentials=False, allow_methods=["GET", "POST"], allow_headers=["Content-Type"])

class Assessment(BaseModel):
    age: int = Field(ge=18, le=120)
    sex: Literal["female", "male", "other"] = "other"
    height: float = Field(ge=50, le=250)
    weight: float = Field(ge=20, le=350)
    glucose: float = Field(ge=40, le=600)
    pressure: float = Field(ge=50, le=260)
    insulin: float | None = Field(default=None, ge=0, le=1000)
    pregnancies: int = Field(default=0, ge=0, le=30)
    family: Literal["yes", "no"] = "no"
    activity: Literal["low", "moderate", "active"] = "moderate"
    diet: Literal["balanced", "high-sugar", "unsure"] = "unsure"
    bmi: float = Field(default=0, ge=0, le=150)

def assess(x: Assessment):
    # Intentionally transparent demo scoring. These weights are not learned or clinically validated.
    bmi = x.weight / ((x.height / 100) ** 2)
    points = 12
    factors = []
    def add(label, impact, detail):
        nonlocal points
        points += impact
        factors.append({"feature": label, "impact": impact, "detail": detail})
    add("Age", min(max(round((x.age - 30) * .35), -6), 14), f"Age entered: {x.age} years. Age is one context factor among many.")
    add("Blood glucose", min(max(round((x.glucose - 95) * .22), -12), 30), f"Entered value: {x.glucose:g} mg/dL. Interpretation depends on timing and clinical context.")
    add("BMI", min(max(round((bmi - 23) * .8), -10), 18), f"Calculated BMI: {bmi:.1f}. BMI is a screening measure, not a diagnosis.")
    add("Blood pressure", min(max(round((x.pressure - 115) * .12), -6), 10), f"Entered systolic value: {x.pressure:g} mmHg.")
    add("Family history", 8 if x.family == "yes" else 0, "Family history selected." if x.family == "yes" else "No family history reported.")
    add("Sex at birth", 0, "Recorded as context only; this demo does not use it to change the score.")
    add("Activity", {"low": 7, "moderate": 2, "active": -4}[x.activity], f"Activity selection: {x.activity}.")
    add("Eating pattern", 5 if x.diet == "high-sugar" else 0, "Eating pattern is self-described and does not measure overall diet quality.")
    probability = min(max(points, 5), 85) / 100
    band = "Higher illustrative" if probability >= .55 else "Moderate illustrative" if probability >= .30 else "Lower illustrative"
    factors.sort(key=lambda f: abs(f["impact"]), reverse=True)
    prompts = ["Ask a clinician whether blood glucose testing is appropriate for you.", "Choose one small, sustainable activity goal that fits your routine.", "Discuss your personal and family history at your next check-up."]
    if bmi >= 25: prompts.insert(1, "If useful, discuss weight, nutrition and supportive options without judgment.")
    return {"id": str(uuid4()), "demo_mode": True, "risk_probability": probability, "risk_band": band, "bmi": round(bmi, 1), "contributions": factors, "counterfactuals": ["A different input can change this illustrative score; that does not establish a causal effect.", "Real risk assessment requires a clinician and a validated approach."], "plan": prompts[:3], "disclaimer": "This rules-based result is illustrative only. It is not generated by a trained model, is not clinically validated, and cannot diagnose or predict an individual’s health."}

@app.get("/health")
def health(): return {"status": "ok", "service": "counterdiab-api", "mode": "educational-demo"}

@app.post("/api/predict")
def predict(payload: Assessment): return assess(payload)

@app.post("/api/assessment")
def assessment(payload: Assessment): return assess(payload)

@app.get("/api/dashboard")
def dashboard(): return {"mode": "educational-demo", "trained_model_available": False, "clinical_validation": False, "metrics": {"accuracy": None, "calibration": None, "auc": None}, "methodology": [{"stage": "Data preparation", "status": "Demo inputs only"}, {"stage": "Prediction", "status": "Transparent illustrative rules"}, {"stage": "Explanation", "status": "Input factor breakdown"}, {"stage": "Counterfactuals", "status": "Educational discussion prompts"}, {"stage": "Validation", "status": "Not performed"}]}
